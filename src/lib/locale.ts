export function isAppLang(v: string | null | undefined): v is AppLang {
  return v === "en" || v === "fr" || v === "ar";
}

export function isAppCurrency(v: string | null | undefined): v is AppCurrency {
  return v === "tnd" || v === "usd" || v === "eur";
}

/**
 * A BCP-47 tag (`ar-TN`, `fr`, `de-DE`…) to a shipped locale, or null when the
 * tag carries no signal. Used for `navigator.languages` on the client and for
 * `Accept-Language` in `src/app/layout.tsx` — the same data, resolved once.
 */
export function languageFromTag(tag: string | null | undefined): AppLang | null {
  if (!tag) return null;
  const t = tag.toLowerCase();
  if (t === "ar" || t.startsWith("ar-")) return "ar";
  if (t === "fr" || t.startsWith("fr-")) return "fr";
  if (t === "en" || t.startsWith("en-")) return "en";
  return null;
}

export function lookup(lang: AppLang, key: string): string | undefined {
  return copy[lang][key];
}

/**
 * Server-side lookup: `generateMetadata` and other server components sit above
 * the provider, so they cannot use `t()`. Same table, same fallback behaviour.
 */
export function translate(lang: AppLang, key: string): string {
  const val: string | undefined = copy[lang][key];
  return val ?? key;
}
