/**
 * Server-safe locale data and helpers.
 *
 * This module deliberately has NO `"use client"` directive. Everything here is
 * pure: types, the EN/FR/AR dictionaries, and the functions that validate a
 * stored preference or resolve a BCP-47 tag to a shipped locale. That matters
 * because `src/app/layout.tsx` and the auth pages' `generateMetadata` run on
 * the SERVER and need `isAppLang` / `translate` / `LANG_DIR` — importing those
 * from a `"use client"` module (`src/lib/i18n.tsx`) makes React refuse the call
 * at runtime ("Attempted to call isAppLang() from the server but isAppLang is
 * on the client") and every route 500s, even though it type-checks and builds.
 *
 * `src/lib/i18n.tsx` re-exports this module's public surface, so importing from
 * either path keeps working. Add new keys to the dictionaries below, in all
 * three locales.
 */

